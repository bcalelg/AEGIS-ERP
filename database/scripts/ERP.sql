      CHECK (REQUIERE_CAMBIAR_PASSWORD IN (0, 1)),
   CONSTRAINT CK_USUARIO_INTENTOS
      CHECK (INTENTOS_ACCESO >= 0),
   CONSTRAINT CK_USUARIO_TELEFONO
      CHECK (TELEFONO_MOVIL IS NULL OR REGEXP_LIKE(TELEFONO_MOVIL, '^[0-9+() -]+$'))

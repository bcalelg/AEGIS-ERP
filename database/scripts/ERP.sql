BEGIN
   FOR t IN (
      SELECT 'BITACORA_ACCESO' AS table_name, 1 AS orden FROM dual UNION ALL
      SELECT 'ROLE_OPCION',     2 FROM dual UNION ALL
      SELECT 'USUARIO',         3 FROM dual UNION ALL
      SELECT 'OPCION',          4 FROM dual UNION ALL
      SELECT 'MENU',            5 FROM dual UNION ALL
      SELECT 'SUCURSAL',        6 FROM dual UNION ALL
      SELECT 'TIPO_ACCESO',     7 FROM dual UNION ALL
      SELECT 'STATUS_USUARIO',  8 FROM dual UNION ALL
      SELECT 'GENERO',          9 FROM dual UNION ALL
      SELECT 'ROLE',           10 FROM dual UNION ALL
      SELECT 'MODULO',         11 FROM dual UNION ALL
      SELECT 'EMPRESA',        12 FROM dual
      ORDER BY orden
   ) LOOP
      BEGIN
         EXECUTE IMMEDIATE
            'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
      EXCEPTION
         WHEN OTHERS THEN
            IF SQLCODE != -942 THEN
               RAISE;
            END IF;
      END;
   END LOOP;
END;

/* Primary keys y sus columnas. */
SELECT c.table_name,
       c.constraint_name,
       LISTAGG(cc.column_name, ', ')
          WITHIN GROUP (ORDER BY cc.position) AS columns_pk
FROM user_constraints c
JOIN user_cons_columns cc
  ON cc.constraint_name = c.constraint_name
 AND cc.table_name = c.table_name
WHERE c.constraint_type = 'P'
  AND c.table_name IN (
     'BITACORA_ACCESO', 'EMPRESA', 'GENERO', 'MENU', 'MODULO',
     'OPCION', 'ROLE', 'ROLE_OPCION', 'STATUS_USUARIO',
     'SUCURSAL', 'TIPO_ACCESO', 'USUARIO'
  )
GROUP BY c.table_name, c.constraint_name
ORDER BY c.table_name, c.constraint_name;

/* Foreign keys, columnas y tabla referenciada. */
SELECT c.table_name,
       c.constraint_name,
       LISTAGG(cc.column_name, ', ')
          WITHIN GROUP (ORDER BY cc.position) AS columns_fk,
       p.table_name AS referenced_table
FROM user_constraints c
JOIN user_cons_columns cc
  ON cc.constraint_name = c.constraint_name
 AND cc.table_name = c.table_name
JOIN user_constraints p
  ON p.constraint_name = c.r_constraint_name
WHERE c.constraint_type = 'R'
  AND c.table_name IN (
     'BITACORA_ACCESO', 'EMPRESA', 'GENERO', 'MENU', 'MODULO',
     'OPCION', 'ROLE', 'ROLE_OPCION', 'STATUS_USUARIO',
     'SUCURSAL', 'TIPO_ACCESO', 'USUARIO'
  )
GROUP BY c.table_name, c.constraint_name, p.table_name
ORDER BY c.table_name, c.constraint_name;

/* Restricciones UNIQUE y sus columnas. */
